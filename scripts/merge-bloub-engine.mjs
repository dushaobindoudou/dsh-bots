#!/usr/bin/env node
/**
 * Merge the vendored bloub engine (tools/bloub/src) into ONE TypeScript block
 * for pasting into src/client.ts.
 *
 * Why: the dsh client entry is a single self-contained file
 * (exports["./client"] → lib/client.js, tsconfig.client.json includes only
 * src/client.ts), so the engine cannot ship as sibling modules. The client
 * must instead carry the engine inline — merged in dependency order with all
 * intra-package imports stripped and `export` keywords removed, so the
 * declarations become locals of client.ts's component scope.
 *
 * The merge is verbatim otherwise: no code edits, so upstream fixes apply by
 * re-vendoring and re-running this script.
 *
 * Usage: node scripts/merge-bloub-engine.mjs > /tmp/bloub-merged.ts
 */
import { readFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = join(HERE, '..', 'tools', 'bloub', 'src')

/**
 * Dependency order. Not the import order: the original modules rely on ESM
 * cycle tolerance (shape.ts consumes profiles.ts's PROFILE_SAMPLES, while
 * profiles.ts uses only shape.ts's TYPES; expressions/eyefit consume
 * face.ts/skins.ts module-initialised tables; eyefit.ts builds its whole
 * offset table at import time by iterating STATES), which a merged scope
 * cannot — const initialisation is strictly sequential here. Type-only edges
 * are erased and so ignored; value edges order this list.
 * cycles.ts is timeline-editor logic the avatar never touches.
 */
const FILES = [
  'math.ts',
  'profiles.ts',
  'shape.ts',
  'repere.ts',
  'face.ts',
  'expressions.ts',
  'decor.ts',
  'skins.ts',
  'states.ts',
  'eyefit.ts',
  'engine.ts',
]

const declared = new Map() // top-level name → file, for duplicate detection

/**
 * Two files legitimately declare a private top-level `ANGLES` (shape.ts and
 * skins.ts build the same sampling grid independently). Rather than editing
 * the vendored sources, the merge prefixes the colliding name within that
 * file's own lines only — the rename is recorded here so a re-vendor that
 * adds a collision fails loudly until it is mapped.
 */
const RENAMES = {
  'skins.ts': { ANGLES: 'SKINS_ANGLES' },
  'states.ts': { pair: 'pairPose' },
}

const out = []
for (const file of FILES) {
  const renames = RENAMES[file] ?? {}
  const raw = readFileSync(join(SRC, file), 'utf8')
  const lines = []
  const srcLines = raw.split('\n')
  for (let i = 0; i < srcLines.length; i += 1) {
    const line = srcLines[i]
    if (/^import\b/.test(line)) {
      // whole import statement: single-line ends on the same line (`from '…'`),
      // multi-line ends at the `} from '…'` closer
      while (i < srcLines.length && !/from\s+'[^']*'\s*;?\s*$/.test(srcLines[i])) i += 1
      continue
    }
    // `export ` stripped so the merged block lives in client.ts's scope;
    // multi-word forms first (export default/interface/type/async function…)
    let merged = line.replace(/\bexport\s+(default\s+)?/g, '')
    for (const [from, to] of Object.entries(renames)) {
      merged = merged.replace(new RegExp(`\\b${from}\\b`, 'g'), to)
    }
    lines.push(merged)
    // track top-level declarations (column 0 only — nested locals share names freely)
    const decl = /^(?:async\s+)?(?:function|class|const|let|var|interface|type|enum)\s+([A-Za-z_$][\w$]*)/.exec(merged)
    if (decl) {
      const owner = declared.get(decl[1])
      if (owner && owner !== file) throw new Error(`duplicate top-level name '${decl[1]}' in ${file} and ${owner}`)
      declared.set(decl[1], file)
    }
  }
  out.push(`// ── ${file} ──────────────────────────────────────────────────────────`)
  out.push(...lines)
}

console.log(`/* ⬇⬇⬇ MERGED BLOUB ENGINE (verbatim from tools/bloub/src, generated by
 * scripts/merge-bloub-engine.mjs — do not edit by hand; re-vendor + re-run).
 * bloub — SVG recreation of the x.ai bot avatar, one shape morphing through
 * 14 measured states. https://github.com/jeremy-prt/bloub — MIT, © Jérémy Perret.
 * Framework-free and clock-free: engine.sample(t) is a pure function of time. */`)
console.log(out.join('\n'))
